#include <unistd.h>

void	ft_countdown(void)
{
	char	i;

	i = '0';
	while(i <= '9')
	{
		write(1, &i, 1);
		i++;
	}
}

int	main(void)
{
	ft_countdown();
	write(1, "\n", 1);
}
