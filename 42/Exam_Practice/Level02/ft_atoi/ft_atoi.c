#include <stdio.h>

int	ft_atoi(const char *str)
{
	int	i;
	int	sign;
	long	result;

	i = 0;
	result = 0;
	sign = 1;
	while (str[i] == 32 || (str[i] >= 9 && str[i] <= 13))
	       i++;
	while (str[i] == '-' || str[i] == '+')
	{
		if(str[i] == '-')
			sign = -sign;
		i++;
	}
	while (str[i] >= '0' && str[i] <= '9')
	{
		result = result * 10 + str[i] - '0';
		i++;
	}
	return (sign * result);
}

int	main(void)
{
	char	str[] = "       			++----+-+-++++---52342172abg6252";
	printf("%d\n", ft_atoi(str));
	return (0);
}
